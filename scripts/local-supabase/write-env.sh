#!/usr/bin/env bash
# Writes .env.development.local so `npm run dev` uses the local Supabase stack. Next.js reads it
# before .env.local in development only, so the production values stay untouched for builds.
set -euo pipefail
cd "$(dirname "$0")/../.."

# Without the stack the values would be empty, and an empty or half-written file would leave Next
# reading .env.local, which points at production. Fail before writing anything.
if ! status_env="$(npx supabase status -o env 2>/dev/null)"; then
  echo "The local Supabase stack is not running. Start it with \`npm run db:start\`." >&2
  exit 1
fi
eval "$status_env"
: "${API_URL:?missing in supabase status}" "${ANON_KEY:?missing in supabase status}" "${SERVICE_ROLE_KEY:?missing in supabase status}"

cat >.env.development.local.partial <<EOF
# Generated by \`npm run db:env\` from \`supabase status\`. Delete it to develop against production.
NEXT_PUBLIC_SUPABASE_URL=$API_URL
NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY
SUPABASE_SERVICE_ROLE_KEY=$SERVICE_ROLE_KEY
NEXT_PUBLIC_APP_URL=http://localhost:3000
# The local Auth has no CAPTCHA, so the widget stays hidden.
NEXT_PUBLIC_TURNSTILE_SITE_KEY=
# The local data has real user emails: with no key, report notifications are skipped and logged.
RESEND_API_KEY=
EOF
mv .env.development.local.partial .env.development.local

echo "Wrote .env.development.local for $API_URL. Restart \`npm run dev\` to pick it up."
